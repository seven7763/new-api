const maps: Record<Lang, Record<string, string> | null> = {
  zh: null,
  en,
  ru,
  vi,
}

export function navTitle(id: string, lang: Lang, fallback: string) {
  const m = maps[lang]
  if (!m) return fallback
  return m[id] || en[id] || fallback
}
